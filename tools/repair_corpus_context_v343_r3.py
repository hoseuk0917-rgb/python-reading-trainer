def clean_spaces(text: str) -> str:
    text = re.sub(r"[ \t]+", " ", str(text or ""))
    text = re.sub(r"\s+([,.;:!?])", r"\1", text)
    return text.strip()


def remove_patterns(text: str, patterns: list[str], min_len: int) -> tuple[str, int]:
    original = str(text or "")
    updated = original
    removed = 0
    for pattern in patterns:
        updated, count = re.subn(pattern, "", updated, flags=re.IGNORECASE)
        removed += count
    updated = clean_spaces(updated)
    if removed and len(updated) >= min_len:
        return updated, removed
    return original, 0


def process(apply_changes: bool) -> tuple[int, int, int, int]:
    files_changed = 0
    cards_changed = 0
    removed_clauses = 0
    targeted = 0
    for path in sorted(EN_ROOT.glob("*.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(payload, list):
            continue
        file_changed = False
        for card in payload:
            if not isinstance(card, dict):
                continue
            changed = False
            cid = str(card.get("id", ""))
            if cid in TARGET_REWRITES and card.get("explanation") != TARGET_REWRITES[cid]:
                card["explanation"] = TARGET_REWRITES[cid]
                targeted += 1
                changed = True
            exp, n1 = remove_patterns(str(card.get("explanation") or ""), EXPLANATION_PATTERNS, 30)
            goal, n2 = remove_patterns(str(card.get("reading_goal") or ""), GOAL_PATTERNS, 18)
            if n1 and exp != card.get("explanation"):
                card["explanation"] = exp
                removed_clauses += n1
                changed = True
            if n2 and goal != card.get("reading_goal"):
                card["reading_goal"] = goal
                removed_clauses += n2
                changed = True
            if changed:
                cards_changed += 1
                file_changed = True
        if file_changed:
            files_changed += 1
            if apply_changes:
                path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return files_changed, cards_changed, removed_clauses, targeted


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.apply == args.check:
        raise SystemExit("choose exactly one of --apply/--check")

    files, cards, removed, targeted = process(args.apply)
    changed = bool(files or cards or removed or targeted)
    print(f"REPAIR_VERSION={VERSION}")
    print(f"APPLY={args.apply}")
    print(f"EN_FILES_CHANGED={files}")
    print(f"EN_CARDS_CHANGED={cards}")
    print(f"GENERIC_CLAUSES_REMOVED={removed}")
    print(f"TARGET_REWRITES={targeted}")
    if args.check:
        print(f"IDEMPOTENT={not changed}")
    ok = not args.check or not changed
    print("RESULT=" + ("PASS_CORPUS_CONTEXT_REPAIR_V343_R3" if ok else "FAIL_CORPUS_CONTEXT_REPAIR_V343_R3"))
    if not ok:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
