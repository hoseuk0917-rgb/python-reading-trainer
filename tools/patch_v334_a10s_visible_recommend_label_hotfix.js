md.push("");
md.push("| target | count |");
md.push("|---|---:|");
for (const change of changes) {
  md.push("| " + change.target + " | " + change.count + " |");
}

fs.writeFileSync(OUT_MD, md.join("\n") + "\n", "utf8");

